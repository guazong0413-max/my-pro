function makeView(id,direction){
  const c=outfit[id], f=faces[id], i=limbData[id][direction],side=direction==="side";
  const arm=near=>({
    high:near?c.near:c.far,low:near?c.near:c.far,highShade:near?c.shade:c.edge,lowShade:near?c.shade:c.edge,
    rim:near?c.seams:null,hem:c.seams,edge:c.edge
  });
  const leg=near=>({
    high:near?c.pants:c.half,low:near?c.pants:c.half,highShade:near?c.pantsShade:null,lowShade:near?c.pantsShade:null,
    rim:near?"#6d7278":null,hem:"#6f7778",edge:c.edge
  });
  const a1=chain("left-arm",i.arm1,arm(!side),hands[id],"arm");
  const a2=chain("right-arm",i.arm2,arm(true),hands[id],"arm");
  const l1=chain("left-leg",{...i.leg1,mirror:!side},leg(!side),shoes(id,direction),"leg");
  const l2=chain("right-leg",{...i.leg2,mirror:false},leg(true),shoes(id,direction),"leg");
  const torso=layer("torso",coat(id,direction));
  const head=layer("head",f[direction],null,side?f.sidePivot:f.pivot);
  const order=side?[...l1,...l2,...a1,torso,...a2,head]:[...l1,...l2,...a1,...a2,torso,head];
  if (id==="uncle") order.push(layer("gear",side?f.gearSide:f.gearFront,"head"));
  return {layers:order};
}

